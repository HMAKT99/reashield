import { createRequire } from "node:module";
import path from "node:path";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);

/**
 * Pillar 3 (Electron): ship V8 bytecode instead of readable JS so the asar
 * holds nothing for REA's JS module-graph path to walk. Uses `bytenode`.
 *
 * IMPORTANT CAVEAT (documented honestly): V8 bytecode is tied to the exact V8
 * version. Compile with the SAME Node/V8 as your target Electron, or the .jsc
 * will not load. This raises cost against automated static JS analysis; it is
 * not unbreakable (bytecode can be disassembled).
 */
export interface BytecodeResult {
  jscPath: string;
  loaderPath: string;
}

export async function compileToBytecode(
  inputFile: string,
  outFile: string,
): Promise<BytecodeResult> {
  let bytenode: { compileFile: (o: { filename: string; output: string }) => Promise<string> | string };
  try {
    bytenode = require("bytenode");
  } catch {
    throw new Error(
      "bytenode is not installed. `npm i -D bytenode` (optional dependency).",
    );
  }
  const jscPath = path.resolve(outFile);
  await bytenode.compileFile({ filename: path.resolve(inputFile), output: jscPath });

  // Tiny loader so the app entry just requires the bytecode.
  const loaderPath = jscPath.replace(/\.jsc$/, "") + ".loader.cjs";
  writeFileSync(
    loaderPath,
    `// Generated by REAShield. Requires bytenode at runtime.\n` +
      `require("bytenode");\nmodule.exports = require(${JSON.stringify(jscPath)});\n`,
  );
  return { jscPath, loaderPath };
}
